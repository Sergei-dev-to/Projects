"""Audit global conformal compactification BEFORE drawing a warp diagram.

Exact signed meridional Alcubierre metric, in lab coordinates:
 g=-dt^2+[dX-b dt]^2+dY^2,
 b=V sech(sqrt((X-Vt)^2+Y^2)), V>1.

The standard Minkowski-to-Einstein-cylinder map covers the entire bulk.
The audit distinguishes regular scri from the defective spatial-infinity
point. It does not identify this map with a boundary-resolved completion.
No figure is generated by this script.
"""
from pathlib import Path

import mpmath as mp
import sympy as sp

mp.mp.dps=70
OUT=Path(__file__).resolve().parents[1]/"output/global_2p1"


def compact(t,x,y):
    r=mp.sqrt(x*x+y*y)
    theta=mp.atan2(y,x) if r else mp.mpf(0)
    u,v=t-r,t+r
    pp,qq=mp.atan(u),mp.atan(v)
    return pp+qq,qq-pp,theta,2/mp.sqrt((1+u*u)*(1+v*v))


def polar_metric(t,x,y,speed=mp.mpf(2)):
    """Exact rescaled metric in (T,chi,theta), evaluated via stable u,v."""
    r=mp.sqrt(x*x+y*y)
    th=mp.atan2(y,x) if r else mp.mpf(0)
    tt,chi,_,omega=compact(t,x,y)
    ratio=mp.sqrt((1+(t+r)**2)/(1+(t-r)**2))
    aa=(ratio+1/ratio)/2
    bb=(ratio-1/ratio)/2
    sine=mp.sin(chi)
    b=speed/mp.cosh(mp.sqrt((x-speed*t)**2+y*y))
    a=mp.matrix([aa,bb,0])
    bx=mp.matrix([bb*mp.cos(th),aa*mp.cos(th),-sine*mp.sin(th)])
    by=mp.matrix([bb*mp.sin(th),aa*mp.sin(th),sine*mp.cos(th)])
    shifted=bx-b*a
    return -a*a.T+shifted*shifted.T+by*by.T


def south_pole_metric(t,x,speed=mp.mpf(2)):
    """Regular pole chart: Z1=(pi-chi)cos(theta), Z2=(pi-chi)sin(theta).

    On Y=0, X>0, dchi=-dZ1 and dtheta=dZ2/(pi-chi).
    This removes the polar-coordinate degeneracy of the base circle.
    """
    tt,chi,_,_=compact(t,x,mp.mpf(0))
    eps=mp.pi-chi
    jac=mp.diag([1,-1,1/eps])
    return jac.T*polar_metric(t,x,mp.mpf(0),speed)*jac


def max_abs(mat):
    return max(abs(mat[i,j]) for i in range(mat.rows) for j in range(mat.cols))


def audit():
    report=[]
    # Algebraic pullback in the orthonormal ESU radial coframe.
    A,B,S,w,c,s=sp.symbols("A B S w c s",real=True)
    a=sp.Matrix([A,B,0])
    bx=sp.Matrix([B*c,A*c,-S*s])
    by=sp.Matrix([B*s,A*s,S*c])
    mat=-a*a.T+(bx-w*a)*(bx-w*a).T+by*by.T
    det=sp.factor(mat.det())
    assert sp.factor(det+S**2*(A**2-B**2)**2*(c*c+s*s)**2)==0
    report.append("Exact global bulk pullback: determinant = -sin(chi)^2; Lorentzian away from ordinary polar axes.")

    # Conformal factor and radial coframe identities.
    T,chi=sp.symbols("T chi",real=True)
    om=sp.cos(T)+sp.cos(chi)
    ap=(1+sp.cos(T)*sp.cos(chi))/om
    bp=sp.sin(T)*sp.sin(chi)/om
    assert sp.trigsimp(ap*ap-bp*bp-1)==0
    t_expr=sp.sin(T)/om
    r_expr=sp.sin(chi)/om
    assert sp.trigsimp(om*sp.diff(t_expr,T)-ap)==0
    assert sp.trigsimp(om*sp.diff(t_expr,chi)-bp)==0
    assert sp.trigsimp(om*sp.diff(r_expr,T)-bp)==0
    assert sp.trigsimp(om*sp.diff(r_expr,chi)-ap)==0
    assert sp.trigsimp((-sp.sin(T)**2+sp.sin(chi)**2).subs(chi,sp.pi-T))==0
    report.append("Inverse map and conformal coframe checked symbolically; ordinary scri has null normal.")

    # Entire original spacetime is covered, not a finite-time tube overlay.
    for t,x,y in [(0,0,0),(2,7,-3),(-20,-40,1),(100,200,mp.mpf('.5'))]:
        t,x,y=map(mp.mpf,(t,x,y))
        tt,rr,th,oo=compact(t,x,y)
        assert abs(tt)+rr<mp.pi
        assert abs(mp.sin(tt)/oo-t)<mp.mpf('1e-60')
        assert abs(mp.sin(rr)*mp.cos(th)/oo-x)<mp.mpf('1e-60')
        assert abs(mp.sin(rr)*mp.sin(th)/oo-y)<mp.mpf('1e-60')
    report.append("Global coordinate round trips passed, including points inside the moving bubble.")

    # Ordinary future/past null infinity: b=O(exp[-(V-1)R]) beats all
    # coordinate powers. Show explicit convergence at regular scri points.
    for sign in (1,-1):
        errors=[]
        for radius in (10,30,100):
            t=mp.mpf(sign*radius)
            x=mp.mpf(radius)*mp.cos(mp.mpf('.7'))
            y=mp.mpf(radius)*mp.sin(mp.mpf('.7'))
            _,rr,_,_=compact(t,x,y)
            flat=mp.diag([-1,1,mp.sin(rr)**2])
            errors.append(max_abs(polar_metric(t,x,y)-flat))
        assert errors[-1]<mp.mpf('1e-35')
        report.append(f"Regular scri {'+' if sign>0 else '-'}: perturbation at R=10,30,100 = "+", ".join(mp.nstr(e,6) for e in errors))

    # A coordinate singularity at i0 must be tested in a REGULAR ESU pole
    # chart, not by looking at the vanishing polar angular coefficient.
    vv=sp.symbols("V",positive=True)
    ac=(vv*vv+1)/(vv*vv-1)
    bc=2*vv/(vv*vv-1)
    aa=sp.Matrix([ac,-bc,0])
    xx=sp.Matrix([bc,-ac,0])
    yy=sp.Matrix([0,0,1])
    core=(-aa*aa.T+(xx-vv*aa)*(xx-vv*aa).T+yy*yy.T).applyfunc(sp.factor)
    core2=core.subs(vv,2)
    expected=sp.Matrix([[sp.Rational(11,9),sp.Rational(2,9),0],
                        [sp.Rational(2,9),-sp.Rational(7,9),0],[0,0,1]])
    assert core2==expected
    flatpole=mp.diag([-1,1,1])
    coretarget=mp.matrix([[mp.mpf(str(z)) if z.q==1 else mp.mpf(int(z.p))/int(z.q) for z in list(expected.row(i))] for i in range(3)])
    rows=[]
    for value in (10,100,1000,10000):
        t=mp.mpf(value)
        center=south_pole_metric(t,2*t)
        escaped=south_pole_metric(t,2*t+mp.sqrt(t))
        rows.append((value,center[0,0],escaped[0,0],max_abs(center-coretarget),max_abs(escaped-flatpole)))
    assert rows[-1][3]<mp.mpf('1e-7')
    assert rows[-1][4]<mp.mpf('.03')
    report.append("Spatial infinity, regular (T,Z1,Z2) chart: center-path limit [[11/9,2/9,0],[2/9,-7/9,0],[0,0,1]].")
    report.append("An exterior path approaching the SAME i0 and SAME first-order direction has limit diag(-1,1,1).")
    report.append("t, center gTT, exterior gTT, center error, exterior error:")
    report.extend("  "+str(row[0])+", "+", ".join(mp.nstr(z,10) for z in row[1:]) for row in rows)
    report.append("FAIL: no continuous nondegenerate metric at i0 in the standard Einstein-cylinder completion.")

    # A scalar replacement of Omega cannot repair non-conformal limiting
    # tensors. Both have transverse YY=1, forcing the same finite rescaling.
    assert sp.factor(core.det()+1)==0
    assert core[2,2]==1
    assert sp.factor(core[0,1])!=0 or sp.factor(core[1,1]-1)!=0
    report.append("A scalar conformal-factor change cannot reconcile these non-proportional metric limits while remaining nondegenerate in the same pole chart.")

    # The background compactified time is not a temporal function for g.
    tt,v=sp.symbols("t V",positive=True)
    dc=sp.diff(sp.atan((1-v)*tt)+sp.atan((1+v)*tt),tt)
    expected_dc=2*(1-(v*v-1)*tt*tt)/((1+(v-1)**2*tt*tt)*(1+(v+1)**2*tt*tt))
    assert sp.factor(dc-expected_dc)==0
    report.append("Center T'(t)=2[1-(V^2-1)t^2]/{[1+(V-1)^2t^2][1+(V+1)^2t^2]}; negative at late positive t.")
    report.append("Radial hyperboloidal tau=t-h(R), h'(R)->1: center d tau/dt -> 1-V<0; it is not a global future time either.")
    report.append("No figure generated: a boundary-resolved construction is still required before claiming the desired global Penrose diagram.")
    OUT.mkdir(parents=True,exist_ok=True)
    text="\n".join(report)+"\n"
    (OUT/"compactification_check.txt").write_text(text,encoding="utf-8")
    print(text)


if __name__=="__main__":
    audit()
