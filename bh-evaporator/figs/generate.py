def gen_j_of_w(output: pathlib.Path):
    matplotlib, plt, np = _import_matplotlib()
    if matplotlib is None:
        return False
    w = np.linspace(0.0, 6.0, 200)
    # Ohmic in-band between [1.5, 4.5]
    J = 0.05 * w
    band_lo, band_hi = 1.5, 4.5
    # Suppress out-of-band
    J[w < band_lo] *= np.exp(-((band_lo - w[w < band_lo])**2))
    J[w > band_hi] *= np.exp(-((w[w > band_hi] - band_hi)**2))
    fig, ax = plt.subplots(figsize=(3.4, 2.6))
    ax.plot(w, J, color="C0")
    ax.axvspan(band_lo, band_hi, color="green", alpha=0.15, label="in-band Ohmic")
    ax.set_xlabel(r"$\omega$")
    ax.set_ylabel(r"$J(\omega)$")
    ax.legend(frameon=False)
    _save_pdf(fig, output, "In-band Ohmic spectral density")
    plt.close(fig)
    return True


