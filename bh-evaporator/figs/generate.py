#!/usr/bin/env python3
"""
Figure generation pipeline.
- Generates figures as PDFs into the LaTeX folder with expected filenames.
- Skips gracefully if dependencies are missing (so LaTeX build still works).
- Embeds Git commit hash in PDF metadata for provenance when available.
"""
from __future__ import annotations

import argparse
import math
import os
import pathlib
import subprocess
import sys
from typing import Callable, Dict


HERE = pathlib.Path(__file__).resolve().parent
PROJECT = HERE.parent


def _import_matplotlib():
    try:
        import matplotlib
        import matplotlib.pyplot as plt
        import numpy as np
    except Exception as exc:
        print(f"[figs] matplotlib/numpy not available: {exc}")
        return None, None, None
    # Reasonable defaults for LaTeX-friendly styling
    matplotlib.rcParams.update({
        "figure.dpi": 150,
        "savefig.dpi": 300,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "axes.grid": True,
        "axes.spines.top": False,
        "axes.spines.right": False,
    })
    return matplotlib, plt, np


def _git_describe() -> str | None:
    try:
        out = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=str(PROJECT))
        return out.decode().strip()
    except Exception:
        return None


def _save_pdf(fig, outpath: pathlib.Path, title: str):
    meta = {"Title": title}
    commit = _git_describe()
    if commit:
        meta["Subject"] = f"Generated by figs/generate.py @ {commit}"
    try:
        fig.savefig(outpath, bbox_inches="tight", metadata=meta)
        print(f"[figs] wrote {outpath.relative_to(PROJECT)}")
    finally:
        pass


def gen_p_of_e(output: pathlib.Path):
    matplotlib, plt, np = _import_matplotlib()
    if matplotlib is None:
        return False
    # Prefer simulation data when available
    spectral = PROJECT / "sim" / "data" / "spectral.npz"
    if spectral.exists():
        dat = np.load(spectral)
        E = dat["E_centers"].astype(float)
        wstar = dat["omega_star"].astype(float)
        mask = np.isfinite(wstar) & (wstar > 0)
        E = E[mask]
        wstar = wstar[mask]
        # Ohmic in-band: J(ω) ∝ ω
        J = wstar
        X = (wstar * J)[:, None]
        y = (1.0 / (E**2))  # expected scaling guide
        # Calibrate beta by least squares so that beta * (w*J) ~ 1/E^2
        beta = float((X.T @ y) / (X.T @ X))
        Pn = beta * (wstar * J)
        # Slope check on log-log: expect ~ -2
        s = (np.polyfit(np.log(E[m2]), np.log(Pn[m2]), 1)[0] if (m2:=np.isfinite(E) & np.isfinite(Pn) & (E>0) & (Pn>0)).sum()>3 else float('nan'))
        if abs(s + 2.0) > 0.3:
            print(f"[check] P(E) slope deviates from -2: {s:.2f}")
    else:
        # Synthetic P(E) ~ beta / E^2 with small multiplicative noise
        beta = 1.0
        E = np.geomspace(1.0, 10.0, 40)
        P = beta / E**2
        noise = np.random.default_rng(1).lognormal(mean=0.0, sigma=0.05, size=E.shape)
        Pn = P * noise

    import matplotlib.gridspec as gridspec
    fig = plt.figure(figsize=(3.6, 3.0))
    gs = gridspec.GridSpec(2, 1, height_ratios=[3, 1], hspace=0.1)
    ax = fig.add_subplot(gs[0])
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.scatter(E, Pn, s=12, label="data")
    ax.plot(E, P, color="C1", label=r"$\propto E^{-2}$")
    ax.set_xlabel("E")
    ax.set_ylabel("P(E)")
    ax.legend(frameon=False)
    # Residuals in log space
    axr = fig.add_subplot(gs[1], sharex=ax)
    resid = np.log(Pn) - np.log(P)
    axr.axhline(0, color="k", lw=0.8)
    axr.plot(E, resid, color="C2")
    axr.set_ylabel("resid")
    axr.set_xlabel("E")
    for label in axr.get_xticklabels():
        label.set_rotation(0)
    _save_pdf(fig, output, "P(E) calibration")
    plt.close(fig)
    return True


def gen_e_of_t(output: pathlib.Path):
    matplotlib, plt, np = _import_matplotlib()
    if matplotlib is None:
        return False
    spectral = PROJECT / "sim" / "data" / "spectral.npz"
    if spectral.exists():
        dat = np.load(spectral)
        Egrid = dat["E_centers"].astype(float)
        wstar = dat["omega_star"].astype(float)
        mask = np.isfinite(wstar) & (wstar > 0)
        Egrid = Egrid[mask]
        wstar = wstar[mask]
        # Fit beta as in gen_p_of_e
        J = wstar
        X = (wstar * J)[:, None]
        y = (1.0 / (Egrid**2))
        beta = float((X.T @ y) / (X.T @ X))
        # Numerical integration of dE/dt = - beta * w*J
        order = np.argsort(Egrid)[::-1]  # high to low energy
        E_sorted = Egrid[order]
        P_sorted = beta * (wstar[order] * J[order])
        # integrate t(E) = ∫ -dE / P(E)
        t = [0.0]
        for i in range(1, len(E_sorted)):
            dE = E_sorted[i] - E_sorted[i-1]
            Pmid = 0.5 * (P_sorted[i] + P_sorted[i-1])
            dt = -dE / max(Pmid, 1e-12)
            t.append(t[-1] + dt)
        t = np.array(t)
        E_num = E_sorted
        # Analytic overlay using E(t) = (E0^3 - 3 beta t)^{1/3}
        E0 = float(E_sorted[0])
        E_ana = (E0**3 - 3.0 * beta * t) ** (1.0 / 3.0)
        En = E_num
        E = E_ana
    else:
        beta = 1.0
        E0 = 10.0
        t = np.linspace(0.0, (E0**3) / (3 * beta) * 0.9, 60)
        E = (E0**3 - 3 * beta * t) ** (1.0 / 3.0)
        rng = np.random.default_rng(2)
        En = E * (1 + rng.normal(0.0, 0.01, size=E.shape))

    import matplotlib.gridspec as gridspec
    fig = plt.figure(figsize=(3.6, 3.0))
    gs = gridspec.GridSpec(2, 1, height_ratios=[3, 1], hspace=0.1)
    ax = fig.add_subplot(gs[0])
    ax.plot(t, E, color="C1", label="prediction")
    ax.scatter(t, En, s=10, color="C0", label="data")
    ax.set_xlabel("t")
    ax.set_ylabel("E(t)")
    ax.legend(frameon=False)
    # Residuals
    axr = fig.add_subplot(gs[1], sharex=ax)
    axr.axhline(0, color="k", lw=0.8)
    axr.plot(t, En - E, color="C2")
    axr.set_ylabel("resid")
    axr.set_xlabel("t")
    _save_pdf(fig, output, "E(t) overlay")
    plt.close(fig)
    return True


TargetGen = Callable[[pathlib.Path], bool]


def gen_s_of_e(output: pathlib.Path):
    matplotlib, plt, np = _import_matplotlib()
    if matplotlib is None:
        return False
    thermo = PROJECT / "sim" / "data" / "thermo.npz"
    if thermo.exists():
        dat = np.load(thermo)
        E = dat["E_centers"].astype(float)
        S2 = dat["S"].astype(float)
        # Estimate a window width for highlighting
        E0 = float(E[len(E)//2])
        w = (E[-1] - E[0]) / (len(E))
    else:
        # Construct an S(E) with a convex intruder window
        E = np.linspace(1.0, 10.0, 200)
        S = 2.0 * np.log(E) + 0.25 * E
        E0, w, amp = 5.0, 1.2, 0.35
        intruder = amp * np.exp(-0.5 * ((E - E0) / (0.45 * w)) ** 2) * (1 - ((E - E0) / w) ** 2)
        S2 = S + intruder
    fig, ax = plt.subplots(figsize=(3.4, 2.6))
    ax.plot(E, S2, label=r"$S(E)$")
    ax.set_xlabel("E")
    ax.set_ylabel("S(E)")
    # Highlight window
    ax.axvspan(E0 - w, E0 + w, color="orange", alpha=0.2, label="convex intruder")
    ax.legend(frameon=False)
    _save_pdf(fig, output, "S(E) with convex intruder")
    plt.close(fig)
    return True


