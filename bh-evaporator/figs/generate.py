def gen_contact_area(output: pathlib.Path):
    matplotlib, plt, np = _import_matplotlib()
    if matplotlib is None:
        return False
    spectral = PROJECT / "sim" / "data" / "spectral.npz"
    if not spectral.exists():
        print("[figs] contact-area: missing spectral data; generate sim/data first")
        return False
    dat = np.load(spectral)
    E = dat["E_centers"].astype(float)
    wstar = dat["omega_star"].astype(float)
    mask = np.isfinite(E) & np.isfinite(wstar) & (E > 0) & (wstar > 0)
    E = E[mask]
    wstar = wstar[mask]
    # Fit beta for M=1 using P ~ beta * w*J with J ~ w
    X = (wstar * wstar)[:, None]
    y = 1.0 / (E**2)
    denom = float(X.T @ X)
    beta = float((X.T @ y) / (denom if denom != 0 else 1.0))
    M_vals = [1, 2, 4]
    import matplotlib.gridspec as gridspec
    fig = plt.figure(figsize=(6.6, 3.0))
    gs = gridspec.GridSpec(1, 2, width_ratios=[1, 1], wspace=0.3)
    # Panel A: P(E) vs E for multiple M
    ax1 = fig.add_subplot(gs[0])
    ax1.set_xscale("log"); ax1.set_yscale("log")
    for M in M_vals:
        Pm = beta * M * (wstar * wstar)
        ax1.plot(E, Pm, label=f"M={M}")
    ax1.set_xlabel("E"); ax1.set_ylabel("P(E)")
    ax1.set_title("Power scales linearly with M")
    ax1.legend(frameon=False)
    # Panel B: E(t) collapse when time scaled by M
    ax2 = fig.add_subplot(gs[1])
    E0 = float(np.max(E))
    tgrid = np.linspace(0.0, 0.9 * (E0**3) / (3 * beta), 80)
    for M in M_vals:
        Et = (E0**3 - 3 * beta * M * tgrid) ** (1.0 / 3.0)
        ax2.plot(M * tgrid, Et, label=f"M={M}")
    ax2.set_xlabel("M t"); ax2.set_ylabel("E")
    ax2.set_title("E vs M t collapses")
    _save_pdf(fig, output, "Contact-area scaling: P and collapse")
    plt.close(fig)
    return True

def targets() -> Dict[str, TargetGen]:
    outdir = PROJECT
    return {
        # map target name to generator function + output filename
        "fig1a_SE": lambda out=outdir / "fig1a_SE.pdf": gen_s_of_e(out),
        "fig1b_T": lambda out=outdir / "fig1b_T.pdf": gen_t_of_e(out),
        "fig2a_J": lambda out=outdir / "fig2a_J.pdf": gen_j_of_w(out),
        "fig2b_omega_star": lambda out=outdir / "fig2b_omega_star.pdf": gen_omega_star(out),
        "fig3_P": lambda out=outdir / "fig3_P.pdf": gen_p_of_e(out),
        "fig4_Et": lambda out=outdir / "fig4_Et.pdf": gen_e_of_t(out),
        "fig5_kappa": lambda out=outdir / "fig5_kappa.pdf": gen_kappa_of_e(out),
        "fig6_pagecurve": lambda out=outdir / "fig6_pagecurve.pdf": gen_page_curve(out),
        "fig7a_distinguishability": lambda out=outdir / "fig7a_distinguishability.pdf": gen_distinguishability(out),
        "fig7b_BLP": lambda out=outdir / "fig7b_BLP.pdf": gen_blp(out),
        "fig8_overlay_EM": lambda out=outdir / "fig8_overlay_EM.pdf": gen_overlay_em(out),
        "fig9_contact_area": lambda out=outdir / "fig9_contact_area.pdf": gen_contact_area(out),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate paper figures")
    parser.add_argument("names", nargs="*", help="Figure names to generate (default: all)")
    parser.add_argument("--only-missing", dest="only_missing", action="store_true", help="Only generate if output is missing")
    args = parser.parse_args(argv)

    gens = targets()
    names = args.names or list(gens.keys())
    ok = True
    for name in names:
        if name not in gens:
            print(f"[figs] unknown figure: {name}")
            ok = False
            continue
        # For lambda closure, we cannot inspect output path easily; rely on missing check per known naming scheme
        if args.only_missing:
            # By convention, file name is <name>.pdf in PROJECT
            out = PROJECT / f"{name}.pdf"
            if out.exists():
                print(f"[figs] skip existing {out.relative_to(PROJECT)}")
                continue
        try:
            res = gens[name]()
            ok = ok and bool(res)
        except Exception as exc:
            print(f"[figs] failed {name}: {exc}")
            ok = False
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())

